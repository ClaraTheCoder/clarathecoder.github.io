import StyleDictionary from 'style-dictionary';
import { writeFileSync, readFileSync, readdirSync, existsSync, unlinkSync } from 'node:fs';

const PRIMITIVE_GROUPS = new Set([
  'lavender',
  'fuchsia',
  'celadon',
  'saffron',
  'cerulean',
  'viridian',
  'vermilion',
  'neutral',
  'black',
  'white',
  'black-alpha',
  'white-alpha',
]);

const primitives = new StyleDictionary({
  usesDtcg: true,
  source: ['src/primitives/**/*.json'],
  platforms: {
    css: {
      transforms: ['name/kebab'],
      buildPath: 'dist/',
      files: [
        { destination: 'primitives.css', format: 'css/variables', options: { selector: ':root' } },
      ],
    },
  },
});
await primitives.buildAllPlatforms();
// Style Dictionary can only write to disk, so capture its output and remove the
// standalone file — every tier is concatenated into a single dist/tokens.css below.
const primitivesCSS = readFileSync(new URL('dist/primitives.css', import.meta.url), 'utf8');
unlinkSync(new URL('dist/primitives.css', import.meta.url));

// Each tier's CSS in cascade order (primitives → semantic → components → utilities),
// written once at the end as the single consumer-facing dist/tokens.css.
const tiers = [primitivesCSS];
console.log('✔︎ primitives tier');

// Replace every {token.path} reference inside a value with var(--token-path),
// passing all other text through untouched — so a bare alias ({color.danger}) and
// a composite value (0 0 0 1px {color.danger}, 0 0 18px {color.danger}) both work.
const resolveRefs = (value) =>
  String(value).replace(/\{([^}]+)\}/g, (_, ref) => `var(--${ref.trim().replace(/\./g, '-')})`);

// Every {reference} inside a value, as dotted token paths.
const refsIn = (value) => [...String(value).matchAll(/\{([^}]+)\}/g)].map((m) => m[1].trim());

async function semanticTokens(mode, preset = 'default') {
  // default theme + (optionally) a preset's partial overrides; later source wins.
  const source = ['src/primitives/**/*.json', `src/semantic/default/color.${mode}.json`];
  if (preset !== 'default') {
    const overrides = `src/semantic/${preset}/color.${mode}.json`;
    if (existsSync(new URL(overrides, import.meta.url))) source.push(overrides);
  }
  const sd = new StyleDictionary(
    {
      usesDtcg: true,
      source,
      platforms: { css: { transforms: ['name/kebab'] } },
    },
    { verbosity: 'silent' },
  );
  const dict = await sd.getPlatformTokens('css');
  return dict.allTokens.filter((t) => t.path[0] === 'color' && !PRIMITIVE_GROUPS.has(t.path[1]));
}

const light = await semanticTokens('light');
const dark = await semanticTokens('dark');

const keysOf = (toks) => toks.map((t) => t.path.join('.')).sort();
const [lk, dk] = [keysOf(light), keysOf(dark)];
const drift = lk.filter((k) => !dk.includes(k)).concat(dk.filter((k) => !lk.includes(k)));
if (drift.length) {
  console.error(`\nSemantic parity failure (light vs dark): ${[...new Set(drift)].join(', ')}\n`);
  process.exit(1);
}

// Set of every tier-1 primitive key, used to validate that preset aliases resolve.
const primJson = JSON.parse(readFileSync(new URL('src/primitives/color.json', import.meta.url)));
const primKeys = new Set();
(function walk(obj, path) {
  for (const [k, v] of Object.entries(obj)) {
    if (k === '$type') continue;
    if (v && typeof v === 'object' && '$value' in v) primKeys.add([...path, k].join('.'));
    else if (v && typeof v === 'object') walk(v, [...path, k]);
  }
})(primJson.color, ['color']);

// Every primitive key across ALL primitive files (color, typography, …), as
// dotted paths — used to validate that typography aliases ({font.size.700}) resolve.
const allPrimKeys = new Set();
for (const f of readdirSync(new URL('src/primitives/', import.meta.url)).filter((n) =>
  n.endsWith('.json'),
)) {
  const json = JSON.parse(readFileSync(new URL(`src/primitives/${f}`, import.meta.url)));
  (function walk(obj, path) {
    for (const [k, v] of Object.entries(obj)) {
      if (k === '$type') continue;
      if (v && typeof v === 'object' && '$value' in v) allPrimKeys.add([...path, k].join('.'));
      else if (v && typeof v === 'object') walk(v, [...path, k]);
    }
  })(json, []);
}

const declare = (toks, pad) =>
  toks.map((t) => `${pad}--${t.path.join('-')}: ${resolveRefs(t.original.$value)};`).join('\n');

const blocks = [
  '/* AUTO-GENERATED by build.js — do not edit by hand. Run `pnpm build`. */',
  '/* Tier 2: semantic tokens (default theme). */',
  `:root {\n${declare(light, '  ')}\n  color-scheme: light;\n}`,
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${declare(dark, '    ')}\n    color-scheme: dark;\n  }\n}`,
  `[data-theme='dark'] {\n${declare(dark, '  ')}\n  color-scheme: dark;\n}`,
  `[data-theme='light'] {\n${declare(light, '  ')}\n  color-scheme: light;\n}`,
];

/**
 * Tier 2 — themed presets.
 *
 * Each src/semantic/<preset>/color.{light,dark}.json is a PARTIAL override of
 * the default theme: any token it omits inherits the default value. Presets are
 * merged over default at build time (later source wins) into a complete set, then
 * emitted scoped to [data-preset='<preset>']. Preset blocks follow the default
 * blocks so the attribute selector wins its specificity tie with :root.
 *
 * Two rules are enforced per preset: every key must exist in the default theme
 * (override-only — presets change values, not the token vocabulary), and every
 * {reference} in a value must resolve to a known token (any tier).
 */
const defaultKeys = new Set(keysOf(light));
// Every token that a value may reference, across tiers. The old "each tier
// references only the one below" rule is dropped so values can carry composite
// content (e.g. box shadows); we still verify each {reference} points at a real
// token so typos fail the build. Component-local keys are added per component below.
const knownRefs = new Set([...primKeys, ...defaultKeys]);
const flatten = (obj, path, out) => {
  for (const [k, v] of Object.entries(obj)) {
    if (k === '$type') continue;
    if (v && typeof v === 'object' && '$value' in v) out.push([[...path, k].join('.'), v.$value]);
    else if (v && typeof v === 'object') flatten(v, [...path, k], out);
  }
  return out;
};

const semanticDir = new URL('src/semantic/', import.meta.url);
const presets = readdirSync(semanticDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== 'default')
  .map((d) => d.name)
  .sort();

for (const preset of presets) {
  const errors = [];
  for (const mode of ['light', 'dark']) {
    const file = new URL(`src/semantic/${preset}/color.${mode}.json`, import.meta.url);
    if (!existsSync(file)) continue;
    for (const [key, value] of flatten(JSON.parse(readFileSync(file)).color ?? {}, ['color'], [])) {
      if (!defaultKeys.has(key))
        errors.push(`${mode}: '${key}' is not a token in the default theme`);
      else {
        for (const ref of refsIn(value)) {
          if (!knownRefs.has(ref))
            errors.push(`${mode}: '${key}' → '{${ref}}' is not a known token`);
        }
      }
    }
  }
  if (errors.length) {
    console.error(
      `\nPreset '${preset}' validation failed:\n` + errors.map((e) => '  ' + e).join('\n') + '\n',
    );
    process.exit(1);
  }

  const pLight = await semanticTokens('light', preset);
  const pDark = await semanticTokens('dark', preset);
  const sel = `[data-preset='${preset}']`;
  blocks.push(
    `/* Preset: ${preset} */`,
    `${sel} {\n${declare(pLight, '  ')}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  ${sel}:not([data-theme='light']) {\n${declare(pDark, '    ')}\n    color-scheme: dark;\n  }\n}`,
    `${sel}[data-theme='dark'] {\n${declare(pDark, '  ')}\n  color-scheme: dark;\n}`,
    `${sel}[data-theme='light'] {\n${declare(pLight, '  ')}\n  color-scheme: light;\n}`,
  );
  console.log(`✔︎ preset '${preset}'`);
}

/**
 * Tier 2 — typography roles (mode-independent composite tokens).
 *
 * Each src/semantic/<theme>/typography.json holds `text.<role>` entries typed
 * as DTCG `typography` composites (following Tokens Studio's superset of
 * sub-properties). We EXPLODE each composite's $value into one custom property
 * per sub-key — `--text-<role>-<css-suffix>` — because CSS has no single property
 * that is "a whole type style" and our theming works by swapping custom props
 * (ADR 0002). Typography does not vary by light/dark, so roles are emitted once:
 * the default theme under `:root`, each preset under `[data-preset='<preset>']`.
 *
 * Gates (minimal, parallel to the colour tiers): presets are override-only
 * (every key must exist in the default theme) and every {reference} must resolve
 * to a known primitive.
 */
const TYPO_SUFFIX = {
  fontFamily: 'font-family',
  fontSize: 'font-size',
  fontWeight: 'font-weight',
  lineHeight: 'line-height',
  letterSpacing: 'letter-spacing',
  textCase: 'text-transform',
  textDecoration: 'text-decoration',
  paragraphSpacing: 'paragraph-spacing',
  paragraphIndent: 'paragraph-indent',
};
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const suffixOf = (sub) => TYPO_SUFFIX[sub] ?? kebab(sub);

// Explode a semantic typography file into [cssVarPath, rawValue] pairs.
const typographyPairs = (file) => {
  if (!existsSync(file)) return [];
  const roles = JSON.parse(readFileSync(file)).text ?? {};
  const out = [];
  for (const [role, def] of Object.entries(roles)) {
    if (role === '$type' || !def || typeof def !== 'object') continue;
    for (const [sub, v] of Object.entries(def.$value ?? {})) {
      out.push([`text.${role}.${suffixOf(sub)}`, v]);
    }
  }
  return out;
};
const declareTypo = (pairs, pad) =>
  pairs.map(([key, v]) => `${pad}--${key.split('.').join('-')}: ${resolveRefs(v)};`).join('\n');

const defaultTypo = typographyPairs(
  new URL('src/semantic/default/typography.json', import.meta.url),
);
if (defaultTypo.length) {
  const defaultTypoKeys = new Set(defaultTypo.map(([key]) => key));
  const typoErrors = [];
  for (const [key, v] of defaultTypo) {
    for (const ref of refsIn(v))
      if (!allPrimKeys.has(ref))
        typoErrors.push(`default: '${key}' → '{${ref}}' is not a known token`);
  }
  if (typoErrors.length) {
    console.error(
      '\nTypography (default) validation failed:\n' +
        typoErrors.map((e) => '  ' + e).join('\n') +
        '\n',
    );
    process.exit(1);
  }
  blocks.push(
    '/* Tier 2: typography roles (mode-independent). */',
    `:root {\n${declareTypo(defaultTypo, '  ')}\n}`,
  );
  console.log('✔︎ typography (default)');

  for (const preset of presets) {
    const pairs = typographyPairs(
      new URL(`src/semantic/${preset}/typography.json`, import.meta.url),
    );
    if (!pairs.length) continue;
    const errors = [];
    for (const [key, v] of pairs) {
      if (!defaultTypoKeys.has(key))
        errors.push(`${preset}: '${key}' is not a typography token in the default theme`);
      for (const ref of refsIn(v))
        if (!allPrimKeys.has(ref))
          errors.push(`${preset}: '${key}' → '{${ref}}' is not a known token`);
    }
    if (errors.length) {
      console.error(
        `\nTypography preset '${preset}' validation failed:\n` +
          errors.map((e) => '  ' + e).join('\n') +
          '\n',
      );
      process.exit(1);
    }
    blocks.push(
      `/* Typography preset: ${preset} */`,
      `[data-preset='${preset}'] {\n${declareTypo(pairs, '  ')}\n}`,
    );
    console.log(`✔︎ typography preset '${preset}'`);
  }
}

/**
 * Tier 2 — base semantic scalars (opacity, …).
 *
 * Mode-independent, non-composite semantic values that are neither colours nor
 * type roles. src/semantic/<theme>/base.json holds flat `<group>.<name>`
 * entries; each emits one `--<group>-<name>` custom property — the default theme
 * under `:root`, each preset under `[data-preset='<preset>']`. Gates mirror the
 * other tiers: presets are override-only and every {reference} must resolve to a
 * known token. (declareTypo is a generic key -> resolveRefs(value) emitter, reused
 * here since base tokens are plain scalars.)
 */
const basePairs = (file) =>
  existsSync(file) ? flatten(JSON.parse(readFileSync(file)), [], []) : [];

const defaultBase = basePairs(new URL('src/semantic/default/base.json', import.meta.url));
if (defaultBase.length) {
  const defaultBaseKeys = new Set(defaultBase.map(([key]) => key));
  const baseErrors = [];
  for (const [key, v] of defaultBase)
    for (const ref of refsIn(v))
      if (!allPrimKeys.has(ref) && !defaultKeys.has(ref))
        baseErrors.push(`default: '${key}' → '{${ref}}' is not a known token`);
  if (baseErrors.length) {
    console.error(
      '\nBase (default) validation failed:\n' + baseErrors.map((e) => '  ' + e).join('\n') + '\n',
    );
    process.exit(1);
  }
  blocks.push(
    '/* Tier 2: base semantic scalars (mode-independent). */',
    `:root {\n${declareTypo(defaultBase, '  ')}\n}`,
  );
  console.log('✔︎ base (default)');

  for (const preset of presets) {
    const pairs = basePairs(new URL(`src/semantic/${preset}/base.json`, import.meta.url));
    if (!pairs.length) continue;
    const errors = [];
    for (const [key, v] of pairs) {
      if (!defaultBaseKeys.has(key))
        errors.push(`${preset}: '${key}' is not a base token in the default theme`);
      for (const ref of refsIn(v))
        if (!allPrimKeys.has(ref) && !defaultKeys.has(ref))
          errors.push(`${preset}: '${key}' → '{${ref}}' is not a known token`);
    }
    if (errors.length) {
      console.error(
        `\nBase preset '${preset}' validation failed:\n` +
          errors.map((e) => '  ' + e).join('\n') +
          '\n',
      );
      process.exit(1);
    }
    blocks.push(
      `/* Base preset: ${preset} */`,
      `[data-preset='${preset}'] {\n${declareTypo(pairs, '  ')}\n}`,
    );
    console.log(`✔︎ base preset '${preset}'`);
  }
}

tiers.push(blocks.join('\n\n') + '\n');
console.log('✔︎ semantic tier');

/**
 * Tier 3 — component tokens.
 *
 * Per-component colour tokens, so the active theme flows through automatically.
 * src/component/<comp>/default.json emits `--<comp>-*` custom properties on the
 * `.<comp>` class. Values may be bare aliases ({color.info}) or composite strings
 * (box shadows etc.); each {reference} resolves to a token on any tier — primitive,
 * semantic, or one of this component's own tokens.
 *
 * Every sibling src/component/<comp>/<preset>.json is a PARTIAL, override-only
 * theme layer, emitted as `[data-preset='<preset>'] .<comp>` after the base block
 * (the compound selector outranks the bare class). Preset keys must be a subset of
 * the base component's, and every {reference} must resolve to a known token.
 */
const flattenAliases = (obj, path, out) => {
  for (const [k, v] of Object.entries(obj)) {
    if (k === '$type') continue;
    if (v && typeof v === 'object' && '$value' in v) out.push([[...path, k], v.$value]);
    else if (v && typeof v === 'object') flattenAliases(v, [...path, k], out);
  }
  return out;
};
const declareComp = (pairs) =>
  pairs.map(([p, value]) => `  --${p.join('-')}: ${resolveRefs(value)};`).join('\n');

const componentDir = new URL('src/component/', import.meta.url);
if (existsSync(componentDir)) {
  const cssBlocks = [
    '/* AUTO-GENERATED by build.js — do not edit by hand. Run `pnpm build`. */',
    '/* Tier 3: component tokens. Reference tier-2 semantics. */',
  ];
  const comps = readdirSync(componentDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  // Base semantic scalars (surface.radius, surface.border-width, focus-ring.*, …)
  // are global custom properties, so components may reference them by validated
  // {…} alias (e.g. {surface.border-width}) instead of raw var(--surface-*)
  // strings that slip past the reference gate (ADR 0003).
  for (const [k] of defaultBase) knownRefs.add(k);

  // Components may also reference any primitive (typography, dimension, …) by a
  // validated {…} alias — not just colour primitives — so type tokens like
  // {font.weight.semibold} go through the integrity gate instead of unchecked raw var().
  for (const k of allPrimKeys) knownRefs.add(k);

  const badAliases = (label, pairs, ownKeys) =>
    pairs.flatMap(([p, value]) =>
      refsIn(value)
        .filter((ref) => !knownRefs.has(ref) && !ownKeys.has(ref))
        .map((ref) => `${label}: '${p.join('.')}' → '{${ref}}' is not a known token`),
    );
  const fail = (label, errors) => {
    if (errors.length) {
      console.error(
        `\n${label} validation failed:\n` + errors.map((e) => '  ' + e).join('\n') + '\n',
      );
      process.exit(1);
    }
  };

  for (const comp of comps) {
    const baseFile = new URL(`src/component/${comp}/default.json`, import.meta.url);
    if (!existsSync(baseFile)) continue;
    const basePairs = flattenAliases(JSON.parse(readFileSync(baseFile)), [], []);
    const baseKeys = new Set(basePairs.map(([p]) => p.join('.')));
    fail(`Component '${comp}'`, badAliases(comp, basePairs, baseKeys));
    cssBlocks.push(`.${comp} {\n${declareComp(basePairs)}\n}`);
    const presetNames = readdirSync(new URL(`src/component/${comp}/`, import.meta.url))
      .filter((n) => n.endsWith('.json') && n !== 'default.json')
      .map((n) => n.replace(/\.json$/, ''))
      .sort();
    for (const preset of presetNames) {
      const file = new URL(`src/component/${comp}/${preset}.json`, import.meta.url);
      if (!existsSync(file)) continue;
      const pairs = flattenAliases(JSON.parse(readFileSync(file)), [], []);
      const errors = pairs
        .filter(([p]) => !baseKeys.has(p.join('.')))
        .map(([p]) => `${preset}: '${p.join('.')}' is not a token on .${comp}`)
        .concat(badAliases(`${comp}/${preset}`, pairs, baseKeys));
      fail(`Component '${comp}' preset '${preset}'`, errors);
      cssBlocks.push(`[data-preset='${preset}'] .${comp} {\n${declareComp(pairs)}\n}`);
      console.log(`✔︎ component '${comp}' preset '${preset}'`);
    }
  }
  tiers.push(cssBlocks.join('\n\n') + '\n');
  console.log('✔︎ component tier');
}

/**
 * Layout utilities — the generated half of the hybrid layout engine
 * (docs/specs/layout-primitives.md, ADR 0002 amendment).
 *
 * The layout primitives (Box/Flex/Grid/Container/Section) are the one component
 * family allowed to emit utility classes, because emitting padding/gap/layout IS
 * their purpose. Their *enumerable* props — the 12-step spacing scale and the
 * flex/grid enums — compile to a finite, bare-named utility layer here; their
 * *arbitrary* values (`width="200px"`, `p="13px"`, …) are carried by inline custom
 * properties the components set, which these same classes read via a
 * per-breakpoint var() fallback chain.
 *
 * Everything lives in the `utilities` cascade layer so that — despite deliberately
 * generic, collision-prone names like `.gap-400` — layer order gives it
 * predictable precedence over the `components`-layer base classes (`.flex` etc.).
 */
const BREAKPOINTS_UTIL = [
  ['xs', '520px'],
  ['sm', '768px'],
  ['md', '1024px'],
  ['lg', '1280px'],
  ['xl', '1640px'],
];

const dimensionJson = JSON.parse(
  readFileSync(new URL('src/primitives/dimension.json', import.meta.url)),
);
const SPACE_STEPS = Object.keys(dimensionJson.space).filter((k) => k !== '$type');

// [classBase, cssProperty, negatable] — scale props. Each emits stepped classes
// (`.p-400`), negatable ones also emit negatives (`.-mt-200`), and every one also
// emits a bare arbitrary class (`.p` reading `var(--p)`) further down.
const SPACING_PROPS = [
  ['p', 'padding', false],
  ['px', 'padding-inline', false],
  ['py', 'padding-block', false],
  ['pt', 'padding-top', false],
  ['pr', 'padding-right', false],
  ['pb', 'padding-bottom', false],
  ['pl', 'padding-left', false],
  ['m', 'margin', true],
  ['mx', 'margin-inline', true],
  ['my', 'margin-block', true],
  ['mt', 'margin-top', true],
  ['mr', 'margin-right', true],
  ['mb', 'margin-bottom', true],
  ['ml', 'margin-left', true],
  ['gap', 'gap', false],
  ['gap-x', 'column-gap', false],
  ['gap-y', 'row-gap', false],
];

// [classPrefix, cssProperty, { tokenValue: cssValue }] — closed enums, stepped only.
const ENUM_PROPS = [
  [
    'direction',
    'flex-direction',
    {
      row: 'row',
      column: 'column',
      'row-reverse': 'row-reverse',
      'column-reverse': 'column-reverse',
    },
  ],
  [
    'align',
    'align-items',
    {
      start: 'flex-start',
      center: 'center',
      end: 'flex-end',
      stretch: 'stretch',
      baseline: 'baseline',
    },
  ],
  [
    'justify',
    'justify-content',
    {
      start: 'flex-start',
      center: 'center',
      end: 'flex-end',
      between: 'space-between',
      around: 'space-around',
    },
  ],
  ['wrap', 'flex-wrap', { nowrap: 'nowrap', wrap: 'wrap', 'wrap-reverse': 'wrap-reverse' }],
  [
    'flow',
    'grid-auto-flow',
    {
      row: 'row',
      column: 'column',
      dense: 'dense',
      'row-dense': 'row dense',
      'column-dense': 'column dense',
    },
  ],
  [
    'display',
    'display',
    {
      none: 'none',
      inline: 'inline',
      'inline-block': 'inline-block',
      block: 'block',
      flex: 'flex',
      'inline-flex': 'inline-flex',
      grid: 'grid',
      'inline-grid': 'inline-grid',
    },
  ],
];

// [classBase, cssProperty] — no scale, no enum: value is always arbitrary, so these
// only ever get the bare arbitrary class + fallback chain.
const ARBITRARY_PROPS = [
  ['width', 'width'],
  ['min-width', 'min-width'],
  ['max-width', 'max-width'],
  ['height', 'height'],
  ['position', 'position'],
  ['inset', 'inset'],
  ['overflow', 'overflow'],
  ['flex-basis', 'flex-basis'],
  ['flex-grow', 'flex-grow'],
  ['flex-shrink', 'flex-shrink'],
  ['grid-column', 'grid-column'],
  ['grid-row', 'grid-row'],
  ['grid-area', 'grid-area'],
  ['columns', 'grid-template-columns'],
  ['rows', 'grid-template-rows'],
];

const rootLines = [];
const mediaLines = Object.fromEntries(BREAKPOINTS_UTIL.map(([bp]) => [bp, []]));
// `xs:` prefixes a class in the file as `.xs\:gap-400`; the `\:` is an escaped
// colon, so the DOM class is literally `xs:gap-400`.
const resp = (bp, selector) => `.${bp}\\:${selector.slice(1)}`;

// Stepped scale classes (+ negatives for margins), initial and per breakpoint.
for (const [base, css, neg] of SPACING_PROPS) {
  for (const step of SPACE_STEPS) {
    rootLines.push(`.${base}-${step} { ${css}: var(--space-${step}); }`);
    if (neg) rootLines.push(`.-${base}-${step} { ${css}: calc(-1 * var(--space-${step})); }`);
    for (const [bp] of BREAKPOINTS_UTIL) {
      mediaLines[bp].push(`${resp(bp, `.${base}-${step}`)} { ${css}: var(--space-${step}); }`);
      if (neg)
        mediaLines[bp].push(
          `${resp(bp, `.-${base}-${step}`)} { ${css}: calc(-1 * var(--space-${step})); }`,
        );
    }
  }
}

// Enum classes, initial and per breakpoint.
for (const [prop, css, values] of ENUM_PROPS) {
  for (const [token, value] of Object.entries(values)) {
    rootLines.push(`.${prop}-${token} { ${css}: ${value}; }`);
    for (const [bp] of BREAKPOINTS_UTIL)
      mediaLines[bp].push(`${resp(bp, `.${prop}-${token}`)} { ${css}: ${value}; }`);
  }
}

// Arbitrary-value classes: a bare class reads `var(--<base>)`, and each breakpoint
// re-reads it through a fallback chain so a responsive object only needs to set the
// custom properties for the rungs it specifies — unspecified rungs inherit the
// nearest smaller one, exactly like the deleted legacy-ds Layout engine.
for (const [base, css] of [...SPACING_PROPS.map(([b, c]) => [b, c]), ...ARBITRARY_PROPS]) {
  rootLines.push(`.${base} { ${css}: var(--${base}); }`);
  let chain = `var(--${base})`;
  for (const [bp] of BREAKPOINTS_UTIL) {
    chain = `var(--${base}-${bp}, ${chain})`;
    mediaLines[bp].push(`.${base} { ${css}: ${chain}; }`);
  }
}

// Nested-primitive inheritance reset (ADR 0008). Custom properties inherit, so an
// ancestor primitive's responsive rung (e.g. `--columns-md`) would otherwise leak
// into a nested primitive and win over that child's own fallback chain. Every
// layout primitive carries the shared `.box` marker; here it declares every
// arbitrary custom property — base rung + each breakpoint rung — to `initial` (the
// guaranteed-invalid value), so an unset rung on the child reads invalid and the
// var() chain falls through to the child's OWN inline rungs. Inline custom
// properties (set per element by resolveLayoutProps) outrank this reset, so rungs
// the child did set still win, and the within-primitive fall-to-nearest-smaller-rung
// behaviour is preserved. `:where()` keeps specificity at 0 so it never stomps
// author styles — it only ever needs to beat inheritance.
const resetBases = [...SPACING_PROPS.map(([b]) => b), ...ARBITRARY_PROPS.map(([b]) => b)];
const resetDecls = resetBases.flatMap((base) => [
  `--${base}: initial;`,
  ...BREAKPOINTS_UTIL.map(([bp]) => `--${base}-${bp}: initial;`),
]);

const classCount = rootLines.length + Object.values(mediaLines).reduce((n, a) => n + a.length, 0);
const utilOut =
  [
    '/* AUTO-GENERATED by build.js — do not edit by hand. Run `pnpm build`. */',
    `/* Layout primitive utilities (ADR 0002). ${classCount} rules. */`,
    '@layer reset, base, components, utilities;',
    '',
    '@layer utilities {',
    '  /* Nested-primitive inheritance reset (ADR 0008). */',
    '  :where(.box) {',
    resetDecls.map((d) => '    ' + d).join('\n'),
    '  }',
    rootLines.map((l) => '  ' + l).join('\n'),
    ...BREAKPOINTS_UTIL.filter(([bp]) => mediaLines[bp].length).map(
      ([bp, min]) =>
        `  @media (min-width: ${min}) {\n` +
        mediaLines[bp].map((l) => '    ' + l).join('\n') +
        '\n  }',
    ),
    '}',
  ].join('\n') + '\n';
tiers.push(utilOut);
console.log(`✔︎ utilities tier (${classCount} rules)`);

writeFileSync(new URL('dist/tokens.css', import.meta.url), tiers.join('\n'));
console.log('✔︎ dist/tokens.css');
